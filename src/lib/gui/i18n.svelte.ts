// ─────────────────────────────────────────────────────────────────────────────
// MARK: GUI i18n — de/en dictionary + reactive t()
// ─────────────────────────────────────────────────────────────────────────────
// * Exactly two locales (the legacy AI-generated fr-FR/it-IT/zh-CN
//   dictionaries were dropped). `t()` reads the live store locale — reactive in
//   component templates because `$state` reads are tracked there.
// * ADR 0014: the dictionaries live in `src/lib/data/i18n.json` and are
//   Base64-decoded at module load (no raw dense text block in the bundle);
//   key types are generated by `scripts/gen-i18n-keys.mjs`.
// * Manual EXAMPLES are locale-free (regex code), only labels/descriptions
//   translate — keeps the dictionary size sane.

import { store } from "../stores/settings.svelte";
import type { Locale, LocaleSetting } from "../core/locale";
import { detectLocale } from "../core/locale";
import { decodeText } from "../core/encoding";
import type { I18nKey } from "./i18n.keys";

/** Dictionary type — both locales MUST keep identical key sets (drift = bug). */
type Dictionary = Record<string, string>;

/** All GUI strings, per locale. Key sets are identical for de and en. */
const TRANSLATIONS: Record<Locale, Dictionary> = JSON.parse(decodeText(__I18N_B64__.join(""))) as Record<
    Locale,
    Dictionary
>;

/** Selectable locale options for the settings tab. */
export const LOCALE_OPTIONS: ReadonlyArray<{ value: LocaleSetting; label: string }> = [
    { value: "auto", label: "Auto" },
    { value: "en", label: "English" },
    { value: "de", label: "Deutsch" },
];

/**
 * Resolves a locale label to a supported locale — unknown values fall back to
 * English.
 *
 * @param locale - The stored/configured locale label.
 */
export function resolveLocale(locale: string | undefined): Locale {
    if (locale === "auto" || locale === undefined) {
        if (locale === "auto") return detectLocale();
        return "en";
    }
    return locale === "de" ? "de" : "en";
}

/**
 * Translates a key with the current store locale — reactive inside component
 * templates (reads `$state`).
 *
 * @param key    - Dictionary key (returned verbatim when missing — makes drift visible).
 * @param params - Optional `{name}` placeholder replacement (e.g. `t("x", { count: 2 })`).
 */
export function t(key: string, params?: Record<string, string | number>): string {
    const dict = TRANSLATIONS[resolveLocale(store.settings.locale)];
    let text = dict[key] ?? key;
    if (params !== undefined) {
        for (const [name, value] of Object.entries(params)) {
            text = text.replaceAll(`{${name}}`, String(value));
        }
    }
    return text;
}

/**
 * Pluralized count string — picks `<key>.one` for exactly one, else `<key>.other`
 * (en/de both need only these two categories).
 *
 * @param key   - Base dictionary key; the dictionary MUST provide `.one` + `.other`.
 * @param count - Number interpolated as `{n}`.
 */
export function tPlural(key: string, count: number): string {
    return t(`${key}.${count === 1 ? "one" : "other"}`, { n: count });
}

export type { I18nKey };
